/**
 * El idioma vivo de la pantalla. `get` cae al castellano si una clave falta, de
 * modo que una traducción incompleta nunca muestra la clave cruda.
 */
class Idioma(val codigo: String) {
    private val tabla = if (codigo == "qu") Textos.QU else Textos.ES
    val quechua: Boolean get() = codigo == "qu"

    operator fun get(clave: String): String =
        tabla[clave] ?: Textos.ES[clave] ?: clave

    fun f(clave: String, vararg valores: Any?): String =
        String.format(get(clave), *valores)

    fun mes(n: Int): String = get("mes.$n")

    fun cultivo(c: pe.yachayallpa.core.Cultivo): String = get("cultivo.${c.name}")
}

val LocalIdioma = staticCompositionLocalOf { Idioma("es") }
